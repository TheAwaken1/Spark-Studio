  var KEY_RE = /^[a-z][a-z0-9_]*(\.[a-z0-9_]+)+$/;

  function lookup(lang, key, vars) {
    var d = I18N[lang] || {};
    var s = d[key];
    if (typeof s !== 'string' && lang !== 'en') s = I18N.en[key];
    if (typeof s !== 'string') return key;
    if (vars) {
      // {plural}: derive from the first numeric variable (n, count, commits...)
      // unless the caller supplies vars.plural explicitly.
      if (s.indexOf('{plural}') !== -1 && vars.plural === undefined) {
        var countVar = null;
        Object.keys(vars).forEach(function (v) {
          if (countVar === null && (typeof vars[v] === 'number' || /^\d+$/.test(String(vars[v])))) {
            countVar = v;
          }
        });
        if (countVar !== null) {
          var num = Number(vars[countVar]);
          vars.plural = (lang === 'fr' ? num > 1 : num !== 1) ? 's' : '';
        }
      }
      Object.keys(vars).forEach(function (v) {
        s = s.split('{' + v + '}').join(vars[v] === undefined ? '' : String(vars[v]));
      });
    }
    return s;
  }

  function detect() {
    try {
      var stored = localStorage.getItem('ss_lang');
      if (stored && I18N[stored]) return stored;
    } catch (e) { /* private mode etc. */ }
    var nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
    return I18N[nav] ? nav : 'en';
  }

